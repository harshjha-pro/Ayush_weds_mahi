"""Turn short headings into SVG outlines set in Pinyon Script (OFL-1.1).

Each letter becomes its own path, so the site can draw them on one after
another (stroke reveal, then the ink fills in). Text is shaped with HarfBuzz,
so joins, kerning and ligatures match the font.

Usage: python3 build_lettering.py <PinyonScript.woff2> <out.js> "Heading" ...
"""
import json
import sys

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

font_path, out_path, *texts = sys.argv[1:]

tt = TTFont(font_path)
tt.flavor = None
tmp = out_path + ".ttf"
tt.save(tmp)
blob = hb.Blob.from_file_path(tmp)
face = hb.Face(blob)
hbfont = hb.Font(face)
glyphs = tt.getGlyphSet()
order = tt.getGlyphOrder()
upm = tt["head"].unitsPerEm
ascent = tt["hhea"].ascent
descent = tt["hhea"].descent

result = {}
for text in texts:
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(hbfont, buf, {"kern": True, "liga": True})
    x = 0
    paths = []
    xmin, xmax = 10**9, -(10**9)
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        name = order[info.codepoint]
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{round(v)}")
        # Font units have y going up; SVG has y going down.
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x + pos.x_offset, ascent - pos.y_offset)))
        d = pen.getCommands()
        if d:
            paths.append(d)
            bounds = glyphs[name]
            xmin = min(xmin, x)
            xmax = max(xmax, x + pos.x_advance)
        x += pos.x_advance
    pad = upm * 0.12
    width = (xmax - xmin) + pad * 2
    height = ascent - descent
    result[text] = {"viewBox": f"{round(xmin - pad)} 0 {round(width)} {round(height)}", "paths": paths}

with open(out_path, "w") as fh:
    fh.write("// Generated by tools/lettering/build_lettering.py from Pinyon Script (SIL Open Font License 1.1).\n")
    fh.write("// One SVG path per letter, so headings can be drawn on stroke by stroke.\n")
    fh.write("export const LETTERING = " + json.dumps(result, separators=(",", ":")) + ";\n")
print(out_path, {k: len(v["paths"]) for k, v in result.items()})
